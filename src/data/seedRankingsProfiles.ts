export function isSeedRankingsProfileId(id: string): boolean {
  return id.startsWith(SEED_ID_PREFIX);
}

/** Count seed profiles eligible for a leaderboard tab. */
export function countSeedEligibleForTab(
  tab: "global" | "boxing" | "mma"
): number {
  return SEED_RANKINGS_PROFILES.filter((profile) => {
    if (tab === "global") {
      return profile.boxing_picks + profile.mma_picks >= 10;
    }
    if (tab === "boxing") return profile.boxing_picks >= 5;
    return profile.mma_picks >= 5;
  }).length;
}
